// runtime hook reads it from state to drive provider-side behavior.
func emitMetaAttr(b *strings.Builder, m typegraph.MetaAttr, tabs string) {
	b.WriteString(fmt.Sprintf("%s%q: schema.BoolAttribute{\n", tabs, m.Name))
	b.WriteString(fmt.Sprintf("%s\tOptional: true,\n", tabs))
	b.WriteString(fmt.Sprintf("%s\tMarkdownDescription: %q,\n", tabs, m.Description))
	b.WriteString(fmt.Sprintf("%s},\n", tabs))
}

// emitDescriptionInt64Validators writes int64 range validators.
func emitDescriptionInt64Validators(b *strings.Builder, prop *typegraph.Property, tabs string) {
	if len(prop.Validators) == 0 {
		return
	}

	var items []string
	for _, v := range prop.Validators {
		if v.Kind != typegraph.ValidatorIntRange {
			continue
		}
		if v.Min != nil && v.Max != nil {
			items = append(items, fmt.Sprintf(
				"%s\t\tint64validator.Between(%d, %d)", tabs, *v.Min, *v.Max))
		} else if v.Min != nil {
			items = append(items, fmt.Sprintf(
				"%s\t\tint64validator.AtLeast(%d)", tabs, *v.Min))
		} else if v.Max != nil {
			items = append(items, fmt.Sprintf(
				"%s\t\tint64validator.AtMost(%d)", tabs, *v.Max))
		}
	}

	if len(items) > 0 {
		b.WriteString(fmt.Sprintf("%s\tValidators: []validator.Int64{\n", tabs))
		for _, item := range items {
			b.WriteString(item + ",\n")
		}
		b.WriteString(fmt.Sprintf("%s\t},\n", tabs))
	}
}

// toExportedGoName converts azapi_storage_account to AzapiStorageAccount.
func toExportedGoName(tfName string) string {
	parts := strings.Split(tfName, "_")
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}

// renderDuration renders a time.Duration as a Go literal for the generated
// descriptor. Timeout values are whole minutes in practice; seconds and a raw
// nanosecond fallback keep the output valid for any value.
func renderDuration(d time.Duration) string {
	switch {
	case d%time.Minute == 0:
		return fmt.Sprintf("%d * time.Minute", d/time.Minute)
	case d%time.Second == 0:
		return fmt.Sprintf("%d * time.Second", d/time.Second)
	default:
		return fmt.Sprintf("%d", int64(d))
	}
}
